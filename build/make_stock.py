#!/usr/bin/env python3
"""
Builds every photograph on the site from licensed stock originals.

    python make_stock.py

Reads   stock/selection.json      which original fills which slot, the crops
                                   each slot needs, focal points, alt text and
                                   full provenance
Reads   ../stock-originals/        the untouched downloads (not in git)
Writes  assets/img/<slot>-<crop>-<width>.{avif,webp,jpg}
Writes  assets/img/manifest.json   read by build.py's {{img}} shortcode
Writes  ../project-docs/STOCK-LICENCES.md   the audit trail for the client

Stock is used for materials, craft and interiors only. It never appears on a
case study and is never captioned as Kroll's work: see the comment at the top
of _pages/case-third-space.html.

Crops
  w  21:9  opening plates          h  16:9  homepage title page
  l  3:2   editorial figures       p  4:5   portraits, material objects
  v  3:4   fixed side panels
  s  1:1   cutaway textures
"""

import os, json
from PIL import Image, ImageOps

ROOT = os.path.dirname(os.path.abspath(__file__))
PROJ = os.path.dirname(ROOT)
SELECTION = os.path.join(ROOT, 'stock', 'selection.json')
ORIGINALS = os.path.join(PROJ, 'stock-originals')
IMG = os.path.join(ROOT, 'assets', 'img')
LICENCES = os.path.join(PROJ, 'project-docs', 'STOCK-LICENCES.md')

RATIOS = {'w': (21, 9), 'h': (16, 9), 'l': (3, 2), 'p': (4, 5), 'v': (3, 4), 's': (1, 1)}
WIDTHS = {'w': [960, 1440, 1920, 2560], 'h': [960, 1440, 1920, 2560],
          'l': [640, 960, 1440, 1920], 'p': [480, 800, 1200, 1600],
          'v': [600, 900, 1400, 2000], 's': [800, 1200]}


def crop_to(im, ratio, focus):
    """Largest crop of the given ratio, centred as near the focal point as the
    frame allows."""
    rw, rh = ratio
    W, H = im.size
    if W / H > rw / rh:
        cw, ch = round(H * rw / rh), H
    else:
        cw, ch = W, round(W * rh / rw)
    fx, fy = focus
    left = min(max(round(fx * W - cw / 2), 0), W - cw)
    top = min(max(round(fy * H - ch / 2), 0), H - ch)
    return im.crop((left, top, left + cw, top + ch))


def emit(im, stem, widths):
    made = []
    for w in widths:
        if w > im.width:
            continue                     # never upscale
        h = round(im.height * w / im.width)
        r = im.resize((w, h), Image.LANCZOS)
        base = os.path.join(IMG, '%s-%d' % (stem, w))
        r.save(base + '.jpg', quality=82, optimize=True, progressive=True)
        r.save(base + '.webp', quality=80, method=6)
        r.save(base + '.avif', quality=52, speed=6)
        made.append((w, h))
    if not made:                         # original smaller than every step
        w = im.width
        base = os.path.join(IMG, '%s-%d' % (stem, w))
        im.save(base + '.jpg', quality=84, optimize=True, progressive=True)
        im.save(base + '.webp', quality=80, method=6)
        im.save(base + '.avif', quality=52, speed=6)
        made.append(im.size)
    return made


def main():
    sel = json.load(open(SELECTION, encoding='utf-8'))
    os.makedirs(IMG, exist_ok=True)
    manifest, rows = {}, []
    for slot, s in sel.items():
        opened = {}
        for crop in s['crops']:
            # A slot can take a different photograph for one crop (a portrait
            # original for the 4:5 crop of a landscape slot, say).
            extra = s.get('crop_files', {}).get(crop)
            fname = extra['file'] if extra else s['file']
            if fname not in opened:
                opened[fname] = ImageOps.exif_transpose(
                    Image.open(os.path.join(ORIGINALS, fname))).convert('RGB')
            im = opened[fname]
            focus = s.get('focus', {}).get(crop, s.get('focus_all', [0.5, 0.5]))
            c = crop_to(im, RATIOS[crop], focus)
            made = emit(c, '%s-%s' % (slot, crop), WIDTHS[crop])
            manifest['%s-%s' % (slot, crop)] = {
                'widths': [w for w, _ in made], 'width': made[-1][0], 'height': made[-1][1],
                'alt': extra['alt'] if extra else s['alt'],
            }
            print('  %-18s %s  %s' % (slot, crop, ', '.join(str(w) for w, _ in made)))
        rows.append(s)
    json.dump(manifest, open(os.path.join(IMG, 'manifest.json'), 'w', encoding='utf-8'), indent=1)

    lines = ['# Stock photography: licences and provenance', '',
             'Generated by `build/make_stock.py` from `build/stock/selection.json`. Every photograph on the',
             'site is listed here with its source, photographer and licence. Case studies use Kroll\'s own',
             'project films only; no stock image is presented as Kroll\'s work anywhere on the site.', '',
             '**Pexels License** and **Unsplash License**: free for commercial use, no attribution required,',
             'no permission needed. Not permitted: selling unaltered copies, implying endorsement by people',
             'or brands shown, or redistributing them as a stock library. Neither licence covers Unsplash+.', '',
             '| Slot | Source | Photographer | Licence | Used as |', '|---|---|---|---|---|']
    def row(slot, s, crops):
        who = s.get('photographer') or 'unknown'
        if s.get('photographer_url'):
            who = '[%s](%s)' % (who, s['photographer_url'])
        return '| `%s` | [%s %s](%s) | %s | %s | %s |' % (
            slot, s['source'].title(), s['id'], s['page_url'], who, s['license'], ', '.join(crops))
    for slot, s in sel.items():
        extras = s.get('crop_files', {})
        lines.append(row(slot, s, [c for c in s['crops'] if c not in extras]))
        for crop, e in extras.items():
            lines.append(row(slot, e, [crop]))
    lines += ['', 'Originals are kept, unedited, in `stock-originals/` (not committed).', '']
    open(LICENCES, 'w', encoding='utf-8').write('\n'.join(lines))
    print('manifest: %d crops, licences: %d photographs' % (len(manifest), len(sel)))


if __name__ == '__main__':
    main()
